const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const Babel = require('@babel/standalone');

const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'homepage-original');
const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'manifest.json'), 'utf8'));

// Refuse accidental edits to the copied original, including the entire footer.
for (const [name, record] of Object.entries(manifest.files)) {
  const bytes = fs.readFileSync(path.join(directory, 'source', name));
  if (createHash('sha256').update(bytes).digest('hex') !== record.sha256) {
    throw new Error(`Original source changed: ${name}. Keep the source snapshot intact.`);
  }
}

function staticHref(href) {
  if (!href.startsWith('/') || href.startsWith('//')) return href;
  const match = href.match(/^([^?#]*)(.*)$/);
  if (match[1] === '/') return 'index.html' + match[2];
  const legal = { '/legal#privacy': 'privacy-policy.html', '/legal#cookie': 'cookie-policy.html', '/legal#terms': 'terms-of-service.html' };
  if (legal[href]) return legal[href];
  const page = match[1].slice(1) + '.html';
  return fs.existsSync(path.join(root, page)) ? page + match[2] : manifest.referenceUrl.replace(/\/$/, '') + href;
}

// Only adapt static route URLs. Component markup, copy, state, and effects are
// compiled directly from the source snapshot, without redesigning them.
function staticLinks() {
  return { visitor: { JSXAttribute(nodePath) {
    const node = nodePath.node;
    if (node.name.name === 'href' && node.value?.type === 'StringLiteral') {
      node.value.value = staticHref(node.value.value);
    }
  } } };
}

const modules = ['part1.jsx', 'part3.jsx', 'part-agents.jsx', 'part-alive.jsx', 'part-enhance.jsx', 'hero-demo.jsx', 'waitlist-flow.jsx'];
const factories = [];
for (const name of [...modules, '../config/importSources.js', 'entry.jsx']) {
  const file = name === 'entry.jsx' ? path.join(directory, name) : path.join(directory, 'source', name);
  const id = name.startsWith('../') ? name : './' + name;
  const code = Babel.transform(fs.readFileSync(file, 'utf8'), {
    presets: [['env', { modules: 'commonjs', targets: { esmodules: true } }], 'react'],
    plugins: [staticLinks], filename: name, comments: false,
  }).code;
  factories.push(`${JSON.stringify(id)}: function(module, exports, require) {\n${code}\n}`);
}

const javascript = `// Generated by scripts/build-homepage.cjs from the pinned original source.\n(function () {\n'use strict';\nconst factories = {\n${factories.join(',\n')}\n};\nconst cache = Object.create(null);\nfunction require(id) {\n  if (id === 'react') return window.React;\n  if (cache[id]) return cache[id].exports;\n  if (!Object.prototype.hasOwnProperty.call(factories, id)) throw new Error('Unknown homepage module: ' + id);\n  const module = { exports: {} };\n  cache[id] = module;\n  factories[id](module, module.exports, require);\n  return module.exports;\n}\nwindow.HomepageOriginal = require('./entry.jsx');\n})();\n`;

const styles = ['styles', 'showcase', 'enhance', 'alive', 'hero-demo', 'polish', 'waitlist-flow', 'waitlist'];
const css = styles.map(name => fs.readFileSync(path.join(directory, 'source/styles', name + '.css'), 'utf8')).join('\n');
for (const [name, content] of [['homepage-original.js', javascript], ['homepage-original.css', css]]) {
  const target = path.join(root, name);
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
}
