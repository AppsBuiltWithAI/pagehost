const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const Babel = require('@babel/standalone');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'homepage/source');
const upstream = JSON.parse(fs.readFileSync(path.join(root, 'homepage/upstream.json'), 'utf8'));
for (const [name, record] of Object.entries(upstream.files)) {
  if (['part1.jsx', 'waitlist-flow.jsx'].includes(name)) continue;
  const bytes = fs.readFileSync(path.join(source, name));
  if (createHash('sha256').update(bytes).digest('hex') !== record.sha256) {
    throw new Error(`Original homepage source changed: ${name}`);
  }
}

// Preserve the original components while resolving routes for static hosting.
function staticUrl(value) {
  if (!value.startsWith('/') || value.startsWith('//')) return value;
  if (value.startsWith('/site/assets/')) return value.slice('/site/'.length);
  const [, pathname, suffix] = value.match(/^([^?#]*)(.*)$/);
  if (pathname === '/') return 'index.html' + suffix;
  if (['/signup', '/signin', '/login'].includes(pathname)) {
    return upstream.referenceUrl.replace(/\/$/, '') + value;
  }
  const page = pathname.slice(1) + '.html';
  if (fs.existsSync(path.join(root, page))) return page + suffix;
  return upstream.referenceUrl.replace(/\/$/, '') + value;
}

function staticLinks() {
  return { visitor: { StringLiteral(nodePath) {
    const parent = nodePath.parent;
    const attribute = parent.type === 'JSXAttribute' && ['href', 'src'].includes(parent.name.name);
    const link = parent.type === 'ObjectProperty' &&
      (parent.key.name === 'href' || parent.key.value === 'href') && parent.value === nodePath.node;
    let expression = nodePath;
    while (expression.parent?.type === 'BinaryExpression' && expression.parent.operator === '+' && expression.parent.left === expression.node) {
      expression = expression.parentPath;
    }
    const assignment = expression.parent;
    const target = assignment?.type === 'AssignmentExpression' && assignment.left;
    const location = target?.type === 'MemberExpression' && target.property.name === 'href' &&
      target.object.type === 'MemberExpression' && target.object.property.name === 'location' &&
      target.object.object.name === 'window';
    if (attribute || link || location) nodePath.node.value = staticUrl(nodePath.node.value);
  } } };
}

const modules = [
  'part1.jsx', 'part3.jsx', 'part-agents.jsx', 'part-alive.jsx',
  'part-enhance.jsx', 'hero-demo.jsx', 'waitlist-flow.jsx', 'waitlist-app.jsx',
  '../config/importSources.js',
];
const supported = new Set(['react', ...modules.map(name => name.startsWith('../') ? name : './' + name)]);
function validateImports() {
  return { visitor: { ImportDeclaration(nodePath) {
    const id = nodePath.node.source.value;
    if (!supported.has(id)) throw new Error(`Unsupported homepage import: ${id}`);
  } } };
}
const factories = modules.map(name => {
  const id = name.startsWith('../') ? name : './' + name;
  const code = Babel.transform(fs.readFileSync(path.join(source, name), 'utf8'), {
    presets: [['env', { modules: 'commonjs', targets: { esmodules: true } }], 'react'],
    plugins: [staticLinks, validateImports], filename: name, comments: false,
  }).code;
  return `${JSON.stringify(id)}: function(module, exports, require) {\n${code}\n}`;
});

const javascript = `// Generated by scripts/build-homepage.cjs. Edit homepage/source instead.\n(function () {\n'use strict';\nconst factories = {\n${factories.join(',\n')}\n};\nconst cache = Object.create(null);\nfunction require(id) {\n  if (id === 'react') return window.React;\n  if (cache[id]) return cache[id].exports;\n  if (!Object.prototype.hasOwnProperty.call(factories, id)) throw new Error('Unknown homepage module: ' + id);\n  const module = { exports: {} };\n  cache[id] = module;\n  factories[id](module, module.exports, require);\n  return module.exports;\n}\nconst Home = require('./waitlist-app.jsx').default;\nwindow.ReactDOM.createRoot(document.getElementById('root')).render(\n  window.React.createElement('div', { className: 'abw-site' }, window.React.createElement(Home))\n);\n})();\n`;

const styles = ['styles', 'showcase', 'enhance', 'alive', 'hero-demo', 'polish', 'waitlist-flow', 'waitlist'];
const css = 'html,body{margin:0;padding:0}\n' + styles.map(name =>
  fs.readFileSync(path.join(source, 'styles', name + '.css'), 'utf8')
).join('\n');
fs.writeFileSync(path.join(root, 'homepage.js'), javascript);
fs.writeFileSync(path.join(root, 'homepage.css'), css);
